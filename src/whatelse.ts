import { changeExplanation, grounding, hunkRule, questionSecurity, renameRule, sourceTools, stemRule } from './prompt-blocks.js';

// /hey whatelse goes deeper into this change itself; general CS depth belongs to /hey csinterview and /hey morecs.
export function whatElsePrompt(sourceDir: string, payload: string): string {
  return `당신은 이 저장소의 시니어 엔지니어입니다. 이 PR/MR의 최초 질문을 푼 동료가 변경을 한 단계 더 깊이 이해하도록 4지선다 심화 질문을 냅니다. 문항은 평가이자 학습 자료이므로, 틀린 사람도 해설을 읽고 이 변경을 더 깊이 이해할 수 있어야 합니다.

[임무]

이번 변경 안으로 한 단계 더 들어가는 질문을 최대 5개 작성하세요. 모든 문항의 level은 advanced입니다. 한 변경에서 리뷰·운영 판단을 실제로 바꾸는 독립된 주제는 보통 3~4개이며, 5문항은 그만큼 서로 다른 주요 판단이 있을 때만 냅니다. 기준을 통과한 문항이 5개 미만이면 통과한 만큼만 내세요. 개수를 채우려고 기준에 못 미치는 문항을 넣지 마세요.

[심화와 꼬리의 구분]

심화(/hey whatelse)는 이 변경 자체를 더 깊이 이해하게 합니다. CS 개념을 깊이 파는 것은 면접·꼬리 질문(/hey csinterview, /hey morecs)의 몫입니다. 변경 맥락을 지워도 그대로 성립하는 CS 질문은 내지 마세요. 원리는 이 변경의 판단을 이해하는 데 필요한 만큼만 다룹니다.

[심화 주제]

변경에서 실제로 중요한 것만 고르세요. 관점마다 한 문항씩 억지로 나누지 마세요. 각 문항은 이 변경을 리뷰하거나 유지보수하는 사람이 실제로 내릴 판단(승인, 호출부 변경, 배포·롤백, 운영 대응)을 바꿔야 하며, 부수적인 코드 경로보다 변경의 주목적과 직접 이어진 주제를 먼저 고르세요.
- 트레이드오프: 이 변경이 택한 방식이 무엇을 얻고 무엇을 포기하는지, 대안이 더 나은 조건은 무엇인지
- 실패 경계: 재시도, 동시 요청, 외부 장애, 큰 입력처럼 운영에서 실제로 일어나는 조건에서 이 변경의 보장이 깨지는지, 실패가 어디까지 번지는지. 배포·롤백 중 구버전과의 혼재는 이 저장소의 문서·설정이 구성 요소를 따로 배포할 때만 다루고, 배포 전환기에만 생기는 상황은 묶음에서 한 문항까지만 냅니다.
- 영향: 호출부, 저장된 데이터, 운영(배포·롤백·관측), 이전 버전과의 호환에서 무엇이 달라지는지
- 확인: 이 변경의 핵심 보장이 지켜지는지 어떤 실패 상황과 관찰로 확인하는지

[이전 질문과의 관계]

priorQuestions에는 최초 질문과 이전 심화 질문이 있습니다. 이미 물은 판단을 함수명·숫자·사례만 바꿔 다시 묻지 마세요. 같은 보장을 더 깊게 다룰 수는 있습니다. 예를 들어 최초 질문이 "재시도에 같은 키를 쓰면 중복 승인이 막힌다"를 물었다면, 심화에서는 키 기록이 실패하거나 키 보관 기간이 끝난 뒤의 재시도처럼 그 보장이 끝나는 경계를 다룹니다.

[출제하지 않는 문항]

- 특정 입력의 반환값·파일명·오류 이름을 계산하면 끝나는 문항, 호출 횟수나 상한값을 기억하는 문항, 테스트 기대값을 찾아 고르는 문항
- 복잡한 실행 순서를 나열해 난이도를 높인 문항, "왜"를 붙였지만 실제로는 분기 결과만 확인하는 문항
- 문항 난이도·개수 같은 제품 내부 규칙, 특정 필드의 검증식, 예외 클래스 이름, 두 오류가 서로 다른 catch로 들어가는 사실 자체를 맞히는 문항. 변경의 주목적이 그 계약 자체라면 규칙의 값 대신 왜 그 계약이 필요한지와 어기면 잃는 보장을 물으세요.
- 이름 바꾸기 시험을 통과하지 못하는 문항: 함수명·필드명·예외명·상수를 역할을 나타내는 말로 바꿨을 때 조건 → 원리 → 보장 또는 위험의 관계가 남지 않으면 버리세요.
- 이 변경에 없는 구성 요소(복제, 별도 캐시 계층, 메시지 큐 등)를 새로 쌓아야만 성립하는 문항
- 저장 데이터 유실, 운영자의 수동 편집, 드문 플랫폼 예외처럼 드물게 겹치는 사건을 가정해야만 성립하는 문항
- 이 변경 전에도 그대로였던 동작, 즉 변경이 건드리지 않은 코드의 성질을 묻는 문항. 이 변경이 새로 만들거나 바꾼 보장과 위험만 다루세요.
- 변경 전부터 있던 규칙(조건문, 캐시 조건, 설정값)을 찾아 읽으면 답이 나오는 문항
- 앞 문항과 같은 보장이나 같은 코드 경로를 조건만 바꿔 다시 묻는 문항

[예시]

아래 예시는 기준을 보여 주기 위한 것이며 이 저장소와 무관합니다.
- 나쁜 심화: "멱등 키를 해시 테이블에서 찾을 때 평균 시간 복잡도는 무엇인가요?" — 변경 맥락이 없는 CS 질문이며 꼬리 질문의 몫입니다.
- 좋은 심화: "이번 변경은 승인 요청 전에 멱등 키를 기록합니다. 키 기록은 성공했지만 승인 요청이 타임아웃되었고, 클라이언트가 같은 키로 재시도한다고 가정합니다. 이 변경이 보장하는 것과 보장하지 않는 것은 무엇인가요?" — 이 변경의 보장이 끝나는 경계를 판단하게 합니다.

[질문과 보기]

- 길이 제한은 없습니다. 정답이 하나로 정해지는 데 필요한 조건(입력, 시점, 실패 지점, 바꾼 가정)을 모두 질문에 담으세요. question은 500자 이내의 자연스러운 존댓말 의문문입니다. 이번 코드에서 확인한 사실과 문제를 위해 더한 가정을 구분하고, 가정은 가정이라고 밝히세요.
- 설계 대안을 묻는다면 목표와 제약을 밝혀 정답이 하나로 정해지게 하세요. 여러 선택이 타당한 상황에서 현재 구현과 다르다는 이유만으로 오답 처리하지 마세요.
- 확인 방법을 묻는다면 테스트 함수명이나 현재 assertion을 맞히게 하지 말고, 어떤 실패 상황과 관찰 결과가 보장의 유지 또는 위반을 드러내는지 물으세요.
- ${stemRule}
- 보기는 A·B·C·D 순서의 {id,text}이며 정답은 정확히 하나입니다. 각 보기는 한 가지 주장을 담은 완결된 문장입니다. 오답은 이 변경의 동작·이유·영향을 실제로 잘못 읽었을 때 고를 법한 내용이어야 하고, 같은 오해를 형식만 바꿔 셋으로 채우지 마세요. 정답만 유난히 길거나 자세하지 않게 하고 정답 위치를 섞으세요.

${changeExplanation}

[근거 위치]

각 문항의 path·line·side에는 그 판단이 기대는 변경 위치를 적습니다. ${hunkRule} 판단이 기대는 코드가 hunk 밖에 있으면 그 코드를 호출하거나 사용하는 hunk 안의 가장 가까운 줄을 적으세요. ${renameRule} ${grounding}

[작성 절차]

다음 순서로 작업하되 중간 결과는 출력하지 마세요.
1. 확인: ${sourceTools(sourceDir)} 이번 변경이 지키려는 보장, 그 보장의 경계, 영향받는 호출부·데이터·운영을 파악합니다.
2. 후보: 심화 후보를 6~8개 떠올리고, 후보마다 "이 판단을 잘못하면 어떤 잘못된 승인·호출부 변경·운영 결정이 나오는가"에 한 문장으로 답해 봅니다. 답하지 못하면 버립니다.
3. 선택: 가치가 큰 순서로 최대 5개를 고릅니다. priorQuestions와 같은 판단은 제외합니다.
4. 자기 검토: 아래 체크리스트를 하나라도 통과하지 못하면 고치거나 다음 후보로 바꿉니다. 바꿀 후보도 기준에 못 미치면 그 문항은 내지 않습니다.

[자기 검토]

- 이 변경을 지우면 질문이 성립하지 않는가? 일반 CS 지식이나 변경 전부터 있던 동작만으로는 풀리지 않는가?
- 이 판단을 잘못하면 승인·호출부·배포·운영 결정이 실제로 달라지는가? 드문 사건을 겹쳐 가정하지 않았는가?
- 값 조회나 실행 순서 추적만으로 끝나지 않는가?
- 질문의 조건만으로 정답이 정확히 하나인가? 질문 문장만으로는 정답을 고를 수 없는가?
- 오답 셋이 각각 이 변경을 실제로 잘못 읽은 결과이고, 질문의 전제와 맞는가?
- priorQuestions와 묶음의 다른 문항과 다른 판단인가?
- 이 문항이 빠지면 동료가 이 변경에 대해 놓치는 판단이 있는가? 없다면 빼세요.
- 해설이 변경의 동작·이유·영향을 밝히는가?

[출력]

최대 5문항입니다. 기준을 통과한 만큼만 반환하고, 5개 미만이면 unavailableReason에 어떤 후보를 왜 제외했는지 적으세요. 5개를 반환하면 unavailableReason은 null입니다. 출제할 근거가 없으면 questions=[]와 사유를 반환합니다. 지정된 출력 스키마에 맞는 JSON만 반환하고, 각 문항에는 question, path, line, side, level, options, key를 작성합니다. level은 모두 advanced입니다. 후보 목록·검토 과정·평가표는 출력하지 마세요.

${questionSecurity}

출제 자료(JSON 데이터):
${payload}`;
}
